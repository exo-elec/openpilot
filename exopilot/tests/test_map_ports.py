"""EOP10's MTSC, MSLC, DDSC and TLSC, ported into exopilot/selfdrive/controls/lib: equivalence with the ORIGINALS' recorded outputs.

`golden_map.json` was generated by running EOP10's original modules (selfdrive/controls/lib/{mtsc,mslc,ddsc,tlsc}.py) on the
built clone, 2026-10-04. Checked first that each original really produces targets (none is dead; DDSC just has no publisher on EOP10).
"""
import json
import math
from pathlib import Path
from types import SimpleNamespace as NS

from exopilot.selfdrive.controls.lib.curve_speed import blend_mtsc_vtsc, calculate_speed_for_curvature
from exopilot.selfdrive.controls.lib.ddsc import DDSC
from exopilot.selfdrive.controls.lib.mslc import MSLC
from exopilot.selfdrive.controls.lib.mtsc import MTSC
from exopilot.selfdrive.controls.lib.tlsc import TLSC

G = json.loads((Path(__file__).parent / 'golden_map.json').read_text())


def same(a, b):
  if a is None or b is None:
    return a is b
  return abs(a - b) < 1e-9


def test_mtsc_reproduces_the_original():
  m = MTSC(enabled=True)
  for row in G['mtsc']:
    r = m.update([(x, y) for x, y in row['curves']], 25.0, 0.0, 0.0)
    assert same(r['v_target'], row['v_target']) and r['state'] == row['state'] and r['is_active'] == row['active']
    assert r['handover_to_vtsc'] == row['handover'] and abs(r['curvature'] - row['curvature']) < 1e-12
    assert same(None if r['distance'] == float('inf') else r['distance'], row['distance'])


def test_mslc_reproduces_the_original():
  s = MSLC(enabled=True)
  for row in G['mslc']:
    # the golden rows are km/h (EOP10's mapData); mapd gives m/s
    target, state = s.update(row['speedLimit'] / 3.6, row['next'] / 3.6, row['dist'], row['v'], row['drv'], row['t'], row['nav'])
    assert same(target, row['target']) and state == row['state']


def test_ddsc_reproduces_the_original():
  d = DDSC()
  for row in G['ddsc']:
    lim, unc, v, gas, lead, stop = row['in']
    cap = d.update(NS(safeSpeedLimitMps=lim, unconsciousActive=unc), NS(gasPressed=gas, vEgo=v, standstill=v < 0.2), lead, stop)
    assert same(cap, row['cap']) and same(d.a_limit, row['a']) and d.active == row['active'] and d.standstill_latched == row['latched']


def test_tlsc_safe_stop_buffer_and_filtering():
  from exopilot.selfdrive.controls.lib.tlsc import TLSC_DECEL, TLSC_STOP_BUFFER

  t = TLSC(enabled=True)
  # Decelerates smoothly toward TLSC_STOP_BUFFER (3.0 m) before the light
  assert same(t.update_from(False, 15.0, [('red', 0.9, 40.0)]), math.sqrt(2.0 * TLSC_DECEL * (40.0 - TLSC_STOP_BUFFER)))
  assert same(t.update_from(False, 15.0, [('yellow', 0.9, 25.0), ('red', 0.9, 60.0)]), math.sqrt(2.0 * TLSC_DECEL * (25.0 - TLSC_STOP_BUFFER)))
  # Critical safety invariant: inside stop buffer (d <= 3.0 m), hold 0.0 m/s instead of dropping TLSC and running the red light
  assert t.update_from(False, 15.0, [('red', 0.9, 3.0)]) == 0.0
  assert t.update_from(False, 3.0, [('red', 0.9, 2.0)]) == 0.0
  assert t.update_from(False, 0.0, [('red', 0.9, 1.5)]) == 0.0
  # Green, lead present, low confidence, beyond max dist, or empty -> None
  assert t.update_from(False, 15.0, [('green', 0.9, 30.0)]) is None
  assert t.update_from(True, 15.0, [('red', 0.9, 40.0)]) is None
  assert t.update_from(False, 15.0, [('red', 0.01, 40.0)]) is None
  assert t.update_from(False, 15.0, [('red', 0.9, 90.0)]) is None
  assert t.update_from(False, 15.0, []) is None
  # Never exceeds current v_ego
  assert t.update_from(False, 3.0, [('red', 0.9, 40.0)]) == 3.0


def test_curve_speed_helpers_and_the_handover_blend():
  assert math.isinf(calculate_speed_for_curvature(0.0005, 1.8)) and abs(calculate_speed_for_curvature(0.004, 1.8) - 21.213) < 1e-3
  assert blend_mtsc_vtsc(20.0, None, 300.0, 25.0, None, 0.05) == (20.0, False)            # MTSC alone beyond 200 m
  assert blend_mtsc_vtsc(None, 18.0, 100.0, 25.0, None, 0.05) == (18.0, False)            # VTSC alone
  assert blend_mtsc_vtsc(20.0, 18.0, 100.0, 25.0, None, 0.05)[0] == 18.0                  # inside 150 m: VTSC
  t, state = blend_mtsc_vtsc(20.0, 18.0, 180.0, 25.0, True, 0.05)                        # transition zone, rate-limited from the cruise speed
  assert abs(t - (25.0 - 1.5 * 0.05)) < 1e-9 and state is True
  assert blend_mtsc_vtsc(None, None, 100.0, 25.0, None, 0.05) == (None, False)
  # both targets beyond 200 m, then the first frame in the zone: already rate-limited (EOP10's rule)
  _, state = blend_mtsc_vtsc(20.0, 18.0, 260.0, 25.0, None, 0.05)
  t, _ = blend_mtsc_vtsc(20.0, 18.0, 190.0, 25.0, state, 0.05)
  assert abs(t - (25.0 - 1.5 * 0.05)) < 1e-9
